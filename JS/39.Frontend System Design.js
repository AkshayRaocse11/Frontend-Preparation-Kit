/**
 * =====================================================
 * FRONTEND SYSTEM DESIGN (INTERVIEW)
 * =====================================================
 *
 * This is asked in senior frontend interviews.
 * Focus is NOT syntax, but architecture.
 */

/**
 * -----------------------------------------------------
 * 1. What is Frontend System Design?
 * -----------------------------------------------------
 *
 * Designing:
 * - Scalable UI
 * - Maintainable code
 * - Performant frontend
 */

/**
 * -----------------------------------------------------
 * 2. Key Questions to Ask (INTERVIEW GOLD)
 * -----------------------------------------------------
 *
 * - Users? Scale?
 * - SEO required?
 * - Performance constraints?
 * - Authentication?
 * - State complexity?
 */

/**
 * -----------------------------------------------------
 * 3. Architecture Layers
 * -----------------------------------------------------
 *
 * UI Layer → Components
 * State Layer → Local / Global
 * Data Layer → API / Cache
 * Utils Layer → Helpers
 */

/**
 * -----------------------------------------------------
 * 4. State Management Decisions
 * -----------------------------------------------------
 *
 * Local state → useState
 * Global state → Context / Redux / Zustand
 * Server state → React Query
 */

/**
 * -----------------------------------------------------
 * 5. Performance Strategies
 * -----------------------------------------------------
 *
 * - Code splitting
 * - Lazy loading
 * - Memoization
 * - Virtualization
 */

/**
 * -----------------------------------------------------
 * 6. API Handling
 * -----------------------------------------------------
 *
 * - Centralized API layer
 * - Retry & error handling
 * - Caching & deduplication
 */

/**
 * -----------------------------------------------------
 * 7. Security Considerations
 * -----------------------------------------------------
 *
 * - Auth tokens
 * - Secure storage
 * - XSS & CSRF protection
 */

/**
 * -----------------------------------------------------
 * 8. Example: Designing a Dashboard
 * -----------------------------------------------------
 *
 * - Authentication
 * - Protected routes
 * - API caching
 * - Role-based UI
 * - Lazy-loaded charts
 */

/**
 * -----------------------------------------------------
 * FINAL INTERVIEW SUMMARY ⭐
 * -----------------------------------------------------
 *
 * - Design for scale
 * - Separate concerns
 * - Optimize rendering
 * - Handle errors & loading
 * - Think UX + performance
 */
